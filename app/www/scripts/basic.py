import sys

def add_numbers(body):

    if body is None:
        return {"error":"missing input body"}

    
    try:
        x = float(body.get("x"))
        y = float(body.get("y"))
        a = float(body.get("a"))
    except (TypeError, ValueError):
        return {"error": "x, y, and a must all be numbers"}

    z = x + y + a

    if x > y:
        answer = "true"
    else:
        answer = "false"

    return(z, answer)

