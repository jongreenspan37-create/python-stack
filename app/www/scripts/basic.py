def add_strings(body):
    body = body or {}

    a = body.get("a")
    b = body.get("b")
    c = body.get("c")
    values = [a, b, c]

    if not all(isinstance(v, str) for v in values):
        return {"error": "a, b, and c must all be strings"}

    if not all(0 < len(v) <= 100 for v in values):
        return {"error": "each word must be between 1 and 100 characters"}

    return {"result": " ".join(values)}

